import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { load } from "js-yaml";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CONTENT_DIR = join(ROOT, "content");
const OUTPUT_DIR = join(ROOT, "build", "cv");

const SITE_URL = "https://leonid.sh/";
const TELEGRAM_URL = "https://t.me/matyushinleonid";

const LABELS = {
  en: {
    education: "Education",
    experience: "Experience (Selected Projects)",
    projects: "Personal Projects",
    achievements: "Other Achievements",
    skills: "Technical Skills",
    email: "Email",
    telegram: "Telegram",
  },
  ru: {
    education: "Образование",
    experience: "Опыт работы",
    projects: "Персональные проекты",
    achievements: "Другие достижения",
    skills: "Технические навыки",
    email: "Email",
    telegram: "Telegram",
  },
};

const LOCALES = Object.keys(LABELS);

const ESCAPES = {
  "\\": "\\textbackslash{}",
  "{": "\\{",
  "}": "\\}",
  $: "\\$",
  "&": "\\&",
  "%": "\\%",
  "#": "\\#",
  _: "\\_",
  "^": "\\textasciicircum{}",
  "~": "\\textasciitilde{}",
  "\u00a0": "~",
  "\u202f": "~",
  "\u2009": "\\,",
};

const ESCAPE_PATTERN = /[\\{}$&%#_^~\u00a0\u202f\u2009]/g;

function tex(value) {
  if (value === undefined || value === null) {
    return "";
  }
  return String(value)
    .replace(/[ \t\n\r]+/g, " ")
    .trim()
    .replace(ESCAPE_PATTERN, (character) => ESCAPES[character])
    .replace(/\*\*(.+?)\*\*/g, "\\textbf{$1}");
}

function technologies(items) {
  if (!items || items.length === 0) {
    return "";
  }
  return `\\textbf{${tex(items.join(", "))}}`;
}

