function heading(cv, labels) {
  const { hero = {}, contact = {}, meta = {} } = cv;
  return [
    "%----------HEADING-----------------",
    "\\begin{tabular*}{\\textwidth}{l@{\\extracolsep{\\fill}}r}",
    `  \\textbf{\\href{${SITE_URL}}{\\Large ${tex(hero.name)}}} & ${tex(labels.email)} : \\href{mailto:${contact.email}}{${tex(contact.email)}}\\\\`,
    `  \\href{${SITE_URL}}{${tex(contact.site)}} & ${tex(labels.telegram)} : \\href{${TELEGRAM_URL}}{${tex(contact.telegram)}} \\\\`,
    "\\end{tabular*}",
    "",
    "\\vspace{5pt}",
    `{\\small ${tex(meta.description)}}`,
  ].join("\n");
}

function education(cv, labels) {
  const entries = cv.education ?? [];
  const lines = [
    "%-----------EDUCATION-----------------",
    `\\section{${tex(labels.education)}}`,
    "  \\resumeSubHeadingListStart",
  ];
  for (const entry of entries) {
    lines.push(
      "    \\resumeSubheading",
      `      {${tex(entry.institution)}}{${tex(entry.location ?? "")}}`,
      `      {${tex(entry.degree)}}{${tex(entry.period)}}`,
    );
  }
  lines.push("  \\resumeSubHeadingListEnd");
  return lines.join("\n");
}

function experience(cv, labels) {
  const entries = cv.experience ?? [];
  const lines = [
    "%-----------EXPERIENCE-----------------",
    `\\section{${tex(labels.experience)}}`,
    "  \\resumeSubHeadingListStart",
  ];
  for (const entry of entries) {
    lines.push(
      "",
      `    \\resumeSubheading{${tex(entry.company)}}{${tex(entry.location)}}{${tex(entry.role)}}{${tex(entry.period)}}`,
    );

    const highlights =
      entry.cvBullets === false ? [] : (entry.highlights ?? []);
    if (highlights.length === 0) {
      continue;
    }

    lines.push("    \\resumeItemListStart");
    for (const highlight of highlights) {
      const stack = technologies(highlight.technologies);
      const body = [tex(highlight.description), stack]
        .filter(Boolean)
        .join(" ");
      lines.push("");
      if (highlight.title) {
        lines.push(
          `    \\resumeItem{${tex(highlight.title)}}`,
          `      {${body}}`,
        );
      } else {
        lines.push(`    \\resumePlainItem{${body}}`);
      }
    }
    lines.push("", "    \\resumeItemListEnd");
  }
  lines.push("", "  \\resumeSubHeadingListEnd");
  return lines.join("\n");
}

function projects(cv, labels) {
  const entries = (cv.projects ?? []).filter(
    (entry) => entry.cvEntry !== false,
  );
  const lines = [
    "%-----------PROJECTS-----------------",
    `\\section{${tex(labels.projects)}}`,
    "  \\resumeSubHeadingListStart",
  ];
  for (const entry of entries) {
    const stack = technologies(entry.technologies);
    const name = entry.href
      ? `\\href{${entry.href}}{${tex(entry.name)}}`
      : tex(entry.name);
    const body = [tex(entry.description), stack].filter(Boolean).join(" ");
    lines.push(`    \\resumeSubItem{${name}}`, `      {${body}}`);
  }
  lines.push("  \\resumeSubHeadingListEnd");
  return lines.join("\n");
}

function achievements(cv, labels) {
  const entries = cv.achievements ?? [];
  const lines = [
    "%-----------OTHER-----------------",
    `\\section{${tex(labels.achievements)}}`,
    "  \\resumeSubHeadingListStart",
  ];
  for (const entry of entries) {
    const meta = [entry.organization, entry.period].filter(Boolean).join(", ");
    const description = tex(entry.description).replace(/\.$/, "");
    const body = meta ? `${description} (${tex(meta)}).` : `${description}.`;
    lines.push(
      "",
      `    \\resumeSubItem{${tex(entry.name)}}`,
      `      {${body}}`,
    );
  }
  lines.push("", "  \\resumeSubHeadingListEnd");
  return lines.join("\n");
}

function skills(cv, labels) {
  const entries = cv.stack ?? [];
  const lines = [
    "%-----------TECHNICAL SKILLS-----------------",
    `\\section{${tex(labels.skills)}}`,
    "  \\resumeSkillListStart",
  ];
  for (const entry of entries) {
    lines.push(`    \\resumeSkillItem{${tex((entry.items ?? []).join(", "))}}`);
  }
  lines.push("  \\resumeSkillListEnd");
  return lines.join("\n");
}

const BABEL_LANGUAGES = {
  en: "russian,english",
  ru: "english,russian",
};

function render(cv, labels, locale) {
  const sections = [
    heading(cv, labels),
    education(cv, labels),
    experience(cv, labels),
    projects(cv, labels),
    achievements(cv, labels),
    skills(cv, labels),
  ];
  const preamble = PREAMBLE.replace("__BABEL__", BABEL_LANGUAGES[locale]);
  return `${preamble}\n\\begin{document}\n\n${sections.join("\n\n\n")}\n\n\\end{document}\n`;
}

async function main() {
  await mkdir(OUTPUT_DIR, { recursive: true });

  for (const locale of LOCALES) {
    const source = join(CONTENT_DIR, `cv.${locale}.yaml`);
    const target = join(OUTPUT_DIR, `cv.${locale}.tex`);
    const cv = load(await readFile(source, "utf8"));
    await writeFile(target, render(cv, LABELS[locale], locale), "utf8");
    process.stdout.write(`${source} -> ${target}\n`);
  }
}

await main();
